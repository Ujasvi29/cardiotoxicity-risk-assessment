"""Portable repository and external dataset paths.

Set ``CARDIOTOXICITY_DATA_ROOT`` to a directory containing the raw CSV files
and optional ``IMAGES`` folder. By default data is read from ``<repo>/dataset``.
Generated project outputs stay under the repository's ignored ``data`` and
``outputs`` directories.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Iterable

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATA_ROOT_ENV = "CARDIOTOXICITY_DATA_ROOT"
RAW_DATA_FILES = (
    "BC_cardiotox_clinical_variables.csv",
    "BC_cardiotox_functional_variable.csv",
    "BC_cardiotox_clinical_and_functional_variables.csv",
)


def get_data_root() -> Path:
    """Return the configured external data directory, independent of cwd."""
    configured = os.environ.get(DATA_ROOT_ENV)
    root = Path(configured).expanduser() if configured else PROJECT_ROOT / "dataset"
    if not root.is_absolute():
        root = PROJECT_ROOT / root
    return root.resolve()


def require_paths(paths: Iterable[Path], *, purpose: str) -> None:
    """Raise an actionable error listing all missing input paths."""
    missing = [Path(path) for path in paths if not Path(path).exists()]
    if not missing:
        return
    expected = "\n".join(f"  - {path}" for path in missing)
    raise FileNotFoundError(
        f"Cannot {purpose}; required input(s) are missing:\n{expected}\n"
        f"Place the original files under {get_data_root()} or set the "
        f"{DATA_ROOT_ENV} environment variable to the directory containing them. "
        "No substitute data is generated by this project."
    )


def require_raw_dataset(*, include_images: bool = False) -> Path:
    """Validate original dataset files without creating or modifying anything."""
    root = get_data_root()
    required = [root / name for name in RAW_DATA_FILES]
    if include_images:
        required.append(root / "IMAGES")
    require_paths(required, purpose="load the original cardiotoxicity dataset")
    if include_images and not any((root / "IMAGES").glob("*.png")):
        raise FileNotFoundError(
            f"No PNG images found under {root / 'IMAGES'}. Extract the original image archive there "
            f"or set {DATA_ROOT_ENV} to the dataset directory."
        )
    return root
